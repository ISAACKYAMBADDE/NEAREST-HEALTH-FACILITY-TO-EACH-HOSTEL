geod = Geod(ellps="WGS84")

results = []

for _, hostel in hostels_df.iterrows():

    hostel_id = hostel["ID"]
    hostel_lat = float(hostel["Latitude"])
    hostel_lon = float(hostel["Longitude"])

    distances = []

    # Compare the hostel with all health facilities
    for _, facility in health_df.iterrows():

        facility_lat = float(facility["Latitude"])
        facility_lon = float(facility["Longitude"])

        # Calculate geodesic distance in metres
        _, _, distance_m = geod.inv(
            hostel_lon,
            hostel_lat,
            facility_lon,
            facility_lat
        )

        distances.append({
            "Health_Centre": facility["ID"],
            "Health_Centre_Latitude": facility_lat,
            "Health_Centre_Longitude": facility_lon,
            "Distance_Metres": distance_m
        })

    # Sort from nearest to farthest
    distances.sort(
        key=lambda item: item["Distance_Metres"]
    )

    # Select the nearest health facility
    nearest = distances[0]

    results.append({
        "Hostel": hostel_id,
        "Hostel_Latitude": hostel_lat,
        "Hostel_Longitude": hostel_lon,
        "Nearest_Health_Centre": nearest["Health_Centre"],
        "Health_Centre_Latitude": nearest[
            "Health_Centre_Latitude"
        ],
        "Health_Centre_Longitude": nearest[
            "Health_Centre_Longitude"
        ],
        "Distance_Metres": nearest["Distance_Metres"],
        "Distance_Kilometres": (
            nearest["Distance_Metres"] / 1000
        )
    })


# Create the results table
nearest_df = pd.DataFrame(results)

