def clean_dataset(df, dataset_name):

    df = df.copy()

    required_columns = ["ID", "Latitude", "Longitude"]

    missing = [
        col for col in required_columns
        if col not in df.columns
    ]

    if missing:
        raise ValueError(
            f"{dataset_name} is missing columns: {missing}"
        )

    # Convert coordinates to numbers
    df["Latitude"] = pd.to_numeric(
        df["Latitude"], errors="coerce"
    )

    df["Longitude"] = pd.to_numeric(
        df["Longitude"], errors="coerce"
    )

    # Remove records with missing coordinates
    df = df.dropna(
        subset=["Latitude", "Longitude"]
    ).copy()

    # Check approximate geographic bounds for Uganda
    valid = (
        df["Latitude"].between(-1.5, 4.5)
        & df["Longitude"].between(29.0, 35.5)
    )

    excluded = int((~valid).sum())
    df = df.loc[valid].copy()

    # Remove duplicate coordinate pairs
    duplicate_count = int(
        df.duplicated(
            subset=["Latitude", "Longitude"]
        ).sum()
    )

    df = df.drop_duplicates(
        subset=["Latitude", "Longitude"]
    ).reset_index(drop=True)

    print(f"\n{dataset_name}")
    print("Valid records:", len(df))
    print("Invalid coordinate records removed:", excluded)
    print("Duplicate coordinate records removed:", duplicate_count)

    return df


